def write(path, sents, group, origin):
    rows = []
    for s in sents:
        rows.append({"text": s, "edits": [], "cats": ["clean"],
                     "origin": origin, "group": group})
    with open(path, "w") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"{path}: {len(rows)} clean sentences")


